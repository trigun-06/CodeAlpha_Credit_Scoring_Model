import { useState } from "react";
import PredictForm from "./components/PredictForm";
import ResultCard from "./components/ResultCard";
import ModelDashboard from "./components/ModelDashboard";
import HistoryTable from "./components/HistoryTable";
import type { Prediction } from "./types";

type Tab = "assess" | "model" | "history";

export default function App() {
  const [tab, setTab] = useState<Tab>("assess");
  const [result, setResult] = useState<Prediction | null>(null);
  const [historyKey, setHistoryKey] = useState(0);

  const handleLogoClick = (e: React.MouseEvent) => {
    e.preventDefault();
    setTab("assess");
    window.scrollTo({ top: 0, behavior: "smooth" });
  };

  return (
    <div className="shell">
      <header className="topbar">
        <a
          href="#assess"
          className="brand"
          onClick={handleLogoClick}
          title="Return to CreditLogic Home"
          aria-label="CreditLogic Home"
        >
          <div className="logo-icon-wrap">
            <span className="logo-symbol">◐</span>
          </div>
          <div className="brand-info">
            <span className="brand-name">CreditLogic</span>
            <span className="brand-badge">AI Risk Engine</span>
          </div>
        </a>

        <nav className="nav-tabs" aria-label="Main Navigation">
          {(
            [
              { id: "assess", label: "Assess", icon: "🎯" },
              { id: "model", label: "Model Insights", icon: "📊" },
              { id: "history", label: "History", icon: "🕒" },
            ] as const
          ).map((t) => (
            <button
              key={t.id}
              className={tab === t.id ? "tab active" : "tab"}
              onClick={() => setTab(t.id)}
            >
              <span className="tab-icon">{t.icon}</span>
              <span>{t.label}</span>
            </button>
          ))}
        </nav>
      </header>

      <main className="main-stage">
        {tab === "assess" && (
          <div className="grid-2 tab-pane">
            <PredictForm
              onResult={(r) => {
                setResult(r);
                setHistoryKey((k) => k + 1);
              }}
            />
            <ResultCard result={result} />
          </div>
        )}
        {tab === "model" && (
          <div className="tab-pane">
            <ModelDashboard />
          </div>
        )}
        {tab === "history" && (
          <div className="tab-pane">
            <HistoryTable refreshKey={historyKey} />
          </div>
        )}
      </main>

      <footer className="footer">
        <p>
          <strong>CreditLogic</strong> &bull; Created &amp; Owned by <strong>Trigun Parvathapuram</strong> &bull; Creditworthiness &amp; Risk Intelligence
        </p>
        <p className="footer-disclaimer">
          Educational project. Predictions are generated by a machine-learning model trained on sample credit data for demonstration purposes only.
        </p>
      </footer>
    </div>
  );
}
